#!/usr/bin/env python3
"""Embed a deterministic Docker build context; Python is a build dependency only."""
import io
import pathlib
import tarfile
root = pathlib.Path(__file__).resolve().parents[1]
files = ['VERSION', 'src/app.c', 'src/terminal.h', 'src/lessons.h', 'src/shell.h', 'src/isolation.h', 'src/tests.c']
buffer = io.BytesIO()
with tarfile.open(fileobj=buffer, mode='w', format=tarfile.USTAR_FORMAT) as archive:
    for name in ['Dockerfile'] + sorted(files):
        data = (root / ('container/Dockerfile' if name == 'Dockerfile' else name)).read_bytes()
        info = tarfile.TarInfo(name)
        info.size, info.mode = len(data), 0o644
        archive.addfile(info, io.BytesIO(data))
data = buffer.getvalue()
with (root / 'src/image_context.h').open('w') as output:
    output.write('/* Generated by scripts/embed-image.py. */\nstatic const unsigned char image_context[] = {\n')
    for offset in range(0, len(data), 32):
        output.write(','.join(str(x) for x in data[offset:offset+32]) + ',\n')
    output.write('};\n')
